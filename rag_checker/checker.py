import re
from typing import List

from configs.model_config import logger

from prompt_definitions import PromptDefinition
from rag_checker.container import RAGResults, RAGResult
from utils.lang_util import lang_def_name


class CustomChecker:
    def __init__(self,
                 custom_llm_api_func=None,
                 **kwargs
    ):
        assert custom_llm_api_func is not None, "custom_llm_api_func is required"
        self.custom_llm_api_func = custom_llm_api_func

    def _fallback_scores(self):
        return {
            "content accuracy": "N/A",
            "completeness": "N/A",
            "relevance": "N/A",
            "conciseness": "N/A",
            "total_score": "N/A"
        }

    def sentence_semantic_check(self, results: RAGResults, **kwargs):
        """
        Perform sentence-level semantic evaluation of the response generated by the model.
        详细查看prompt参考：en/semantic_evaluator_prompt.json
        """
        total_score_key = "total_score"
        _fallback_scores = {
            "content accuracy": "N/A",
            "completeness": "N/A",
            "relevance": "N/A",
            "conciseness": "N/A",
            total_score_key: "N/A"
        }

        def _parse_evaluation_scores(response: str) -> dict:
            """
            Parse the evaluation scores from the model response.

            Parameters
            ----------
            response : str
                The response string from the model containing the evaluation scores.

            Returns
            -------
            dict
                A dictionary with the evaluation criteria as keys and their corresponding scores as values.
            """
            criteria = ["content accuracy", "completeness", "relevance", "conciseness"]
            weights = {"content accuracy": 0.6,  "completeness": 0.2, "relevance": 0.1, "conciseness": 0.1}
            scores = {}

            # Normalize the response by stripping whitespace and converting to lowercase
            normalized_response = response.strip().lower()

            for criterion in criteria:
                criterion_weight = weights.get(criterion, 0)
                try:
                    matches = re.findall(rf"{criterion}:\s*(\d+)", normalized_response)
                    if matches and len(matches) > 0:
                        scores[criterion] = float(matches[-1]) * criterion_weight
                    else:
                        scores[criterion] = 0
                except Exception as e:
                    logger.error(f"Error parsing evaluation score for criterion '{criterion}': {e}")
                    scores[criterion] = 0

            total_score = round(sum(scores.values()), 1) / 100
            scores[total_score_key] = total_score
            return scores

        rag_results: List[RAGResult] = results.results
        var0 = []
        for i, item in enumerate(rag_results):
            if (system_prompt_str := kwargs.get("system_prompt", None)) is None:
                system_prompt = PromptDefinition.load_builtin_prompt_static(lang=lang_def_name(is_chinese_text=False),
                                                                                 prompt_name="semantic_evaluator_prompt")
                few_shot_samples_dict = PromptDefinition.load_prompt_json_dict_static(lang=lang_def_name(is_chinese_text=False),
                                                                                 prompt_name="semantic_evaluator_few_shot_examples")
                system_prompt_str = system_prompt.format(
                    question=item.query,
                    gt_answer=item.gt_answer,
                    llm_response=item.response,
                    few_shot_examples=few_shot_samples_dict.get("standard_few_shot_examples1", "")
                )
            var0.append(system_prompt_str)

            if len(var0) == kwargs.get("batch_size", 8):
                responses = []
                try:
                    responses = self.custom_llm_api_func(var0)
                except Exception as e:
                    logger.exception(f"Error in request sentence_semantic_check: {e}")

                for j, response in enumerate(responses):
                    scores = _fallback_scores
                    try:
                        scores = _parse_evaluation_scores(response)
                    except Exception as e:
                        logger.exception(f"Error in parse sentence_semantic_check: {e}")
                    rag_results[i - len(var0) + j].sentence_check_answer2response = [scores.get(total_score_key, 0)]
                    rag_results[i - len(var0) + j].sentence_check_points = scores
                var0 = []

        if len(var0) > 0:
            responses = []
            try:
                responses = self.custom_llm_api_func(var0)
            except Exception as e:
                logger.exception(f"Error in request sentence_semantic_check: {e}")
            for j, response in enumerate(responses):
                scores = _fallback_scores
                try:
                    scores = _parse_evaluation_scores(response)
                except Exception as e:
                    logger.exception(f"Error in parse sentence_semantic_check: {e}")
                rag_results[-len(var0) + j].sentence_check_answer2response = [scores.get(total_score_key, 0)]
                rag_results[-len(var0) + j].sentence_check_points = scores

        return results